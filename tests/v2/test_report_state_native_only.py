"""STATE.md 里的数字只能有一个来源：``acceptance.json``。

2026-11-13 收尾时发现 native-only 那张表还是手抄的，dark 写着 95.51，
产物算出来是 95.49 —— 手抄的账又漂了一次。所以这张表并进生成块，
并留下一条守卫：文档里的数字块必须等于现算结果，表头只能出现一次。
"""

from __future__ import annotations

import json

import pytest

from scripts import report_state
from scripts.report_state import END, BEGIN, render_block


def _page(label: str, *, within30=90.0, native_only=90.0, coverage=0.0, **extra):
    page = {
        "label": label,
        "status": "blocked-fail",
        "within30": within30,
        "nativeOnly": (
            None
            if native_only is None
            else {
                "within30": native_only,
                "coveredRatio": coverage,
                "regionCount": 3,
            }
        ),
        "criticalPassed": 18,
        "criticalTotal": 18,
        "nativePassed": 14,
        "nativeTotal": 18,
        "bridgeBuild": "2026-11-11-multiline-rotation",
        "buildMatches": True,
        "gitSha": "a" * 40,
        "strategies": [],
        "failureCounts": {},
    }
    page.update(extra)
    return page


def test_native_only_table_is_rendered_from_the_pages():
    block = render_block(
        [
            _page("holdout", within30=94.80, native_only=94.76, coverage=0.0072),
            _page("light-form", within30=92.21, native_only=86.24, coverage=0.513),
        ]
    )

    assert "| 页面 | within30 | native-only | 位图覆盖 |" in block
    assert "| holdout | 94.80 | 94.76 | 0.7% |" in block


def test_a_page_that_pastes_a_lot_is_emphasised():
    block = render_block(
        [
            _page("light-form", within30=92.21, native_only=86.24, coverage=0.513),
            _page("dark", within30=95.46, native_only=95.49, coverage=0.001),
        ]
    )

    assert "| light-form | 92.21 | **86.24** | **51.3%** |" in block
    assert "| dark | 95.46 | 95.49 | 0.1% |" in block


def test_a_page_without_native_only_still_gets_a_row():
    block = render_block([_page("legacy", native_only=None)])

    assert "| 页面 | within30 | native-only | 位图覆盖 |" in block
    assert "| legacy | 90.00 | — | — |" in block


def test_write_replaces_only_the_marker_block(tmp_path, monkeypatch):
    target = tmp_path / "STATE.md"
    target.write_text(
        f"前情提要，不许被覆盖。\n\n{BEGIN}\n旧内容\n{END}\n\n后面的纪律，也不许动。\n",
        encoding="utf-8",
    )

    monkeypatch.setattr(report_state, "collect", lambda: [_page("p1")])
    assert report_state.main(["--write", str(target)]) == 0

    text = target.read_text(encoding="utf-8")
    assert text.startswith("前情提要，不许被覆盖。")
    assert text.rstrip().endswith("后面的纪律，也不许动。")
    assert "旧内容" not in text
    assert "| p1 | 90.00 | 18/18 | 14/18 | 是 |" in text


def test_page_reads_native_only_out_of_the_acceptance_report(tmp_path):
    run = tmp_path / "run"
    run.mkdir()
    (run / "acceptance.json").write_text(
        json.dumps(
            {
                "status": "blocked-fail",
                "visual": {
                    "within30_pct": 92.21,
                    "native_only": {
                        "within30_pct": 86.24,
                        "covered_pixel_ratio": 0.513,
                        "region_count": 31,
                    },
                },
                "critical_text": {"matched_count": 24, "required_count": 24},
                "native_text_quality": {
                    "gate": {"nativeText": {"ownerPassCount": 30, "ownerCount": 33}}
                },
                "runtime": {
                    "bridgeBuild": "b",
                    "buildMatches": True,
                    "gitSha": "c" * 40,
                },
            }
        ),
        encoding="utf-8",
    )

    page = report_state._page("light-form", run)

    assert page is not None
    assert page["nativeOnly"] == {
        "within30": 86.24,
        "coveredRatio": 0.513,
        "regionCount": 31,
    }
    assert page["within30"] == 92.21


def test_an_older_report_without_native_only_degrades_to_none(tmp_path):
    run = tmp_path / "run"
    run.mkdir()
    (run / "acceptance.json").write_text(
        json.dumps({"visual": {"within30_pct": 95.47}}), encoding="utf-8"
    )

    page = report_state._page("dark", run)

    assert page is not None
    assert page["nativeOnly"] is None


@pytest.mark.skipif(not report_state.collect(), reason="没有本地产物，无法对账")
def test_the_committed_block_is_what_the_script_would_generate():
    """文档不许有手抄版本：现算结果与 docs/STATE.md 里的块必须逐行一致。"""
    doc = (report_state.ROOT / "docs" / "STATE.md").read_text(encoding="utf-8")
    head, rest = doc.split(BEGIN, 1)
    documented, _ = rest.split(END, 1)
    documented = BEGIN + documented + END

    def without_timestamp(text: str) -> list[str]:
        return [
            line
            for line in text.splitlines()
            if not line.startswith("<!-- generated by scripts/report_state.py at ")
        ]

    assert (
        without_timestamp(documented)
        == without_timestamp(render_block(report_state.collect()))
    ), "docs/STATE.md 与产物对不上：跑 `python scripts/report_state.py --write docs/STATE.md`"


@pytest.mark.skipif(
    not (report_state.ROOT / "docs" / "STATE.md").is_file(), reason="没有 STATE.md"
)
def test_the_native_only_table_appears_only_once_and_inside_the_block():
    doc = (report_state.ROOT / "docs" / "STATE.md").read_text(encoding="utf-8")
    header = "| 页面 | within30 | native-only | 位图覆盖 |"

    assert doc.count(header) == 1
    assert BEGIN in doc and END in doc
    assert doc.index(BEGIN) < doc.index(header) < doc.index(END)
